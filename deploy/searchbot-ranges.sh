#!/usr/bin/env bash
# Writes deploy/searchbots/ranges.caddy: the address ranges Google and Bing
# publish for their crawlers, as Caddy `client_ip` lines. deploy/Caddyfile
# imports the file into `(search_engine_landing)` (ADR-0098), so a request from
# one of those ranges may fetch the landing pages that robots.txt allows.
#
# Prints `changed` when the file's contents changed and `unchanged` when they
# did not; deploy-on-box.sh recreates the proxy on `changed`, since Caddy reads
# imports only at start. A failed fetch, a list that does not parse, or a list
# shorter than MIN_PREFIXES leaves the existing file as it was and exits 1.
# With no file at all the matcher matches nobody.
#
#   bash deploy/searchbot-ranges.sh
set -euo pipefail

cd "$(dirname "$0")"
OUT_DIR=searchbots
OUT="$OUT_DIR/ranges.caddy"
GOOGLE_URL="${GOOGLE_URL:-https://developers.google.com/static/search/apis/ipranges/googlebot.json}"
BING_URL="${BING_URL:-https://www.bing.com/toolbox/bingbot.json}"
MIN_PREFIXES="${MIN_PREFIXES:-10}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -fsS --max-time 30 --retry 3 --retry-delay 2 -A "linkedlegislation-deploy" \
    -o "$work/google.json" "$GOOGLE_URL"
curl -fsS --max-time 30 --retry 3 --retry-delay 2 -A "linkedlegislation-deploy" \
    -o "$work/bing.json" "$BING_URL"

python3 -I - "$MIN_PREFIXES" "$work/google.json" "$work/bing.json" > "$work/ranges.caddy" <<'PY'
import ipaddress
import json
import sys

minimum = int(sys.argv[1])
print("# Generated by deploy/searchbot-ranges.sh. Not committed (ADR-0098).")
for name, path in zip(("Google", "Bing"), sys.argv[2:]):
    with open(path, encoding="utf-8") as fh:
        prefixes = json.load(fh)["prefixes"]
    nets = sorted(
        {ipaddress.ip_network(p.get("ipv4Prefix") or p["ipv6Prefix"]) for p in prefixes},
        key=lambda n: (n.version, n),
    )
    if len(nets) < minimum:
        sys.exit(f"{name}: {len(nets)} prefixes, fewer than {minimum}")
    print(f"# {name}: {len(nets)} prefixes")
    for i in range(0, len(nets), 16):
        print("client_ip " + " ".join(str(n) for n in nets[i:i + 16]))
PY

mkdir -p "$OUT_DIR"
if [ -f "$OUT" ] && cmp -s "$work/ranges.caddy" "$OUT"; then
    echo unchanged
else
    mv "$work/ranges.caddy" "$OUT"
    chmod 644 "$OUT"
    echo changed
fi
