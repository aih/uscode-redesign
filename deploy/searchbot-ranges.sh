#!/usr/bin/env bash
# Writes deploy/searchbots/ranges.caddy: the address ranges Google and Bing
# publish for their crawlers, as Caddy `client_ip` lines. deploy/Caddyfile
# imports the file into `(search_engine_landing)` (ADR-0098), so a request from
# one of those ranges may fetch the landing pages that robots.txt allows.
#
# Prints `changed` when the file's contents changed and `unchanged` when they
# did not; deploy-on-box.sh recreates the proxy on `changed`, since Caddy reads
# imports only at start. A list that fails to fetch or parse, or is shorter
# than MIN_PREFIXES, is left out and named on stderr. When neither list is
# usable the existing file stays as it was and the script exits 1.
# With no file at all the matcher matches nobody.
#
#   bash deploy/searchbot-ranges.sh
set -euo pipefail

cd "$(dirname "$0")"
OUT_DIR=searchbots
OUT="$OUT_DIR/ranges.caddy"
GOOGLE_URL="${GOOGLE_URL:-https://developers.google.com/static/search/apis/ipranges/googlebot.json}"
BING_URL="${BING_URL:-https://www.bing.com/toolbox/bingbot.json}"
MIN_PREFIXES="${MIN_PREFIXES:-10}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# -L: either address may answer with a redirect, and without it curl saves
# the redirect's empty body and exits 0.
for source in google bing; do
    url="$GOOGLE_URL"; [ "$source" = bing ] && url="$BING_URL"
    curl -fsSL --max-time 30 --retry 3 --retry-delay 2 -A "linkedlegislation-deploy" \
        -o "$work/$source.json" "$url" \
        || { echo "$source: fetch of $url failed" >&2; rm -f "$work/$source.json"; }
done

# Each list is read on its own: one that fails to parse or is too short is
# reported on stderr and left out, and the file is written from the others.
# With neither, nothing is written and the script exits 1.
python3 -I - "$MIN_PREFIXES" "$work/google.json" "$work/bing.json" > "$work/ranges.caddy" <<'PY'
import ipaddress
import json
import sys

minimum = int(sys.argv[1])
lines = []
for name, path in zip(("Google", "Bing"), sys.argv[2:]):
    try:
        with open(path, "rb") as fh:
            body = fh.read()
    except OSError:
        continue
    try:
        prefixes = json.loads(body)["prefixes"]
        nets = sorted(
            {ipaddress.ip_network(p.get("ipv4Prefix") or p["ipv6Prefix"]) for p in prefixes},
            key=lambda n: (n.version, n),
        )
    except (ValueError, KeyError, TypeError) as exc:
        print(f"{name}: not a range list ({exc}); {len(body)} bytes, starting {body[:120]!r}", file=sys.stderr)
        continue
    if len(nets) < minimum:
        print(f"{name}: {len(nets)} prefixes, fewer than {minimum}", file=sys.stderr)
        continue
    lines.append(f"# {name}: {len(nets)} prefixes")
    lines += ["client_ip " + " ".join(str(n) for n in nets[i:i + 16]) for i in range(0, len(nets), 16)]
if not lines:
    sys.exit("no usable range list")
print("# Generated by deploy/searchbot-ranges.sh. Not committed (ADR-0098).")
print("\n".join(lines))
PY

mkdir -p "$OUT_DIR"
if [ -f "$OUT" ] && cmp -s "$work/ranges.caddy" "$OUT"; then
    echo unchanged
else
    mv "$work/ranges.caddy" "$OUT"
    chmod 644 "$OUT"
    echo changed
fi
